import AppKit
import UniformTypeIdentifiers
import os

private let logger = Logger(subsystem: "com.tray.app", category: "TypeDetector")

enum TypeDetector {

    /// Determines ClipboardItemType from pasteboard contents.
    /// Priority order: file > url > image > richText > html > color > tabularData > plainText
    static func detect(from pasteboard: NSPasteboard) -> (type: ClipboardItemType, metadata: ClipboardItemMetadata)? {
        guard let types = pasteboard.types else { return nil }

        var metadata = ClipboardItemMetadata()

        // File URL
        if types.contains(.fileURL),
           let url = pasteboard.string(forType: .fileURL),
           let fileURL = URL(string: url) {
            metadata.filePath = fileURL.path
            metadata.fileName = fileURL.lastPathComponent
            if let attrs = try? FileManager.default.attributesOfItem(atPath: fileURL.path) {
                metadata.fileSize = attrs[.size] as? Int64
            }
            return (.file, metadata)
        }

        // URL
        if types.contains(NSPasteboard.PasteboardType("public.url")),
           let urlString = pasteboard.string(forType: .string) ?? pasteboard.string(forType: NSPasteboard.PasteboardType("public.url")),
           URL(string: urlString) != nil {
            metadata.urlString = urlString
            metadata.plainText = urlString
            return (.url, metadata)
        }

        // Image
        let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff]
        for imgType in imageTypes {
            if types.contains(imgType), let data = pasteboard.data(forType: imgType) {
                if let image = NSImage(data: data), image.size.width.isFinite, image.size.height.isFinite {
                    metadata.imageWidth = Int(image.size.width)
                    metadata.imageHeight = Int(image.size.height)
                }
                return (.image, metadata)
            }
        }

        // Rich text
        if types.contains(.rtf), let data = pasteboard.data(forType: .rtf) {
            metadata.rtfData = data
            if let plain = pasteboard.string(forType: .string) {
                metadata.plainText = plain
            }
            return (.richText, metadata)
        }

        // HTML — many apps (Notion, Google Docs, browsers) put styled text as HTML.
        // Only classify as .html if no plain text fallback exists (i.e. it's raw HTML).
        // Otherwise treat it as rich text since the user copied styled content, not code.
        if types.contains(.html), let html = pasteboard.string(forType: .html) {
            metadata.htmlString = html
            if let plain = pasteboard.string(forType: .string) {
                metadata.plainText = plain
                // Has plain text → user copied styled content, classify as rich text
                return (.richText, metadata)
            }
            // No plain text fallback → actual HTML content
            return (.html, metadata)
        }

        // Color (NSColor pasteboard)
        if types.contains(NSPasteboard.PasteboardType("com.apple.cocoa.pasteboard.color")) {
            if let color = NSColor(from: pasteboard)?.usingColorSpace(.sRGB) {
                let r = color.redComponent
                let g = color.greenComponent
                let b = color.blueComponent
                let a = color.alphaComponent
                metadata.colorRGBA = [Double(r), Double(g), Double(b), Double(a)]
                metadata.colorHex = String(format: "#%02X%02X%02X", byte(r), byte(g), byte(b))
                return (.color, metadata)
            }
        }

        // Plain text (check for tabular first)
        if types.contains(.string), let text = pasteboard.string(forType: .string) {
            metadata.plainText = text

            // Tabular detection: text with tabs and multiple lines in grid pattern
            if isTabular(text) {
                let rows = text.components(separatedBy: .newlines).filter { !$0.isEmpty }
                let cols = rows.first?.components(separatedBy: "\t").count ?? 0
                metadata.rowCount = rows.count
                metadata.columnCount = cols
                metadata.tsvData = text
                return (.tabularData, metadata)
            }

            return (.plainText, metadata)
        }

        return nil
    }

    /// Markers apps set (nspasteboard.org) for content that shouldn't be kept:
    /// passwords (1Password etc.), temporary clipboard use by automation tools,
    /// and content generated rather than copied by the user
    private static let ignoredTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    static func shouldIgnore(pasteboard: NSPasteboard) -> Bool {
        guard let types = pasteboard.types else { return false }
        return ignoredTypes.contains(where: types.contains)
    }

    /// Generates a content preview string for display
    static func preview(for type: ClipboardItemType, metadata: ClipboardItemMetadata) -> String {
        switch type {
        case .plainText, .richText, .html:
            let text = metadata.plainText ?? metadata.htmlString ?? ""
            // Collapse newlines/tabs to single spaces for single-line display
            let collapsed = text.components(separatedBy: .newlines).joined(separator: " ")
                .components(separatedBy: .whitespaces).filter { !$0.isEmpty }.joined(separator: " ")
            return String(collapsed.prefix(200))
        case .url:
            return metadata.urlString ?? "URL"
        case .image:
            let w = metadata.imageWidth ?? 0
            let h = metadata.imageHeight ?? 0
            return "Image \(w) × \(h)"
        case .file:
            return metadata.fileName ?? "File"
        case .color:
            return metadata.colorHex ?? "Color"
        case .tabularData:
            let r = metadata.rowCount ?? 0
            let c = metadata.columnCount ?? 0
            return "Table \(r)×\(c)"
        }
    }

    // MARK: - Private

    /// 0...1 color component → 0...255. Clamped: extended-range or NaN components
    /// would otherwise trap in Int()
    static func byte(_ component: CGFloat) -> Int {
        guard component.isFinite else { return 0 }
        return Int((min(max(component, 0), 1) * 255).rounded())
    }

    private static func isTabular(_ text: String) -> Bool {
        let lines = text.components(separatedBy: .newlines).filter { !$0.isEmpty }
        guard lines.count >= 2 else { return false }
        let firstTabCount = lines[0].components(separatedBy: "\t").count
        guard firstTabCount >= 2 else { return false }
        // Check that at least half the lines have the same column count
        let matching = lines.filter { $0.components(separatedBy: "\t").count == firstTabCount }.count
        return matching >= lines.count / 2
    }
}
